"""Bounded validation of Unreal Singapore sensor-fusion campaign artifacts.

This module validates simulation telemetry and capture integrity.  It does not
claim physical RF calibration, real-world performance, or engagement ability.
All input reads are bounded and all reported model/ground-truth comparisons are
explicitly scoped to scenario truth generated by the simulator.
"""

