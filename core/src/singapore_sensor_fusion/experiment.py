"""Bounded one-shot experiment over Unreal sensor-fusion exports.

This runner is detection-only.  RF observations are generated by the labeled
analytic energy-detector fallback; the unavailable SiRFNet preprocessing is
never guessed and the RF checkpoints are never deserialized.  Event inference
is optional and consumes ``proxy_event_stack_v1`` images, which are explicitly
not equivalent to the supplied checkpoint's training preprocessing.

Run with::

    python -m singapore_sensor_fusion.experiment \
        --saved-dir <TRIAD_PROJECT>\\Saved\\SingaporeSensorFusion \
        --output experiment_report.json
"""

