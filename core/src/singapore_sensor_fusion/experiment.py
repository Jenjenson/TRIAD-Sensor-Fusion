_RGB_FRAME_PATTERN = re.compile(
    # UE's FDateTime formatter emits a literal ``f`` for the plugin's current
    # ``%f`` token.  Accept that deployed form as well as numeric fractions;
    # the sibling depth JSON remains the authoritative UTC timestamp.
    r"^frame_(?P<index>\d+)_(?P<timestamp>\d{8}T\d{6}(?:\d{1,6}|f)Z)_rgb\.png$",
    re.IGNORECASE,
)


class MissingOptionalDependencyError(RuntimeError):
    """A requested optional image dependency is unavailable."""


@dataclass(frozen=True, slots=True)
class FramePair:
    node_id: str
    previous_path: Path
    current_path: Path


def _deduplicate(items: Iterable[str]) -> list[str]:
    return list(dict.fromkeys(item for item in items if item))


def _positive_bounded(name: str, value: int, hard_limit: int) -> int:
    if isinstance(value, bool) or not isinstance(value, int):
        raise TypeError(f"{name} must be an integer")
    if value < 1 or value > hard_limit:
        raise ValueError(f"{name} must be in [1, {hard_limit}]")
    return value


def _finite_number(name: str, value: object) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise TypeError(f"{name} must be a number")
    result = float(value)
    if not math.isfinite(result):
        raise ValueError(f"{name} must be finite")
    return result


def _nonempty_string(name: str, value: object) -> str:
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{name} must be a non-empty string")
    return value.strip()


def _parse_utc_timestamp(value: object, *, fallback: datetime) -> tuple[datetime, bool]:
    if isinstance(value, str) and value.strip():
        normalized = value.strip()
        if normalized.endswith("Z"):
            normalized = normalized[:-1] + "+00:00"
        try:
            parsed = datetime.fromisoformat(normalized)
            if parsed.tzinfo is None or parsed.utcoffset() is None:
                parsed = parsed.replace(tzinfo=timezone.utc)
            return parsed.astimezone(timezone.utc), False
        except ValueError:
            pass
    return fallback.astimezone(timezone.utc), True


def find_newest_rf_telemetry(saved_dir: str | Path) -> Path | None:
    """Return the newest session JSONL by mtime, then by name."""

    directory = Path(saved_dir).expanduser().resolve()
    candidates = [path for path in directory.glob("rf_links_*.jsonl") if path.is_file()]
    if not candidates:
        return None
    return max(candidates, key=lambda path: (path.stat().st_mtime_ns, path.name))


def read_bounded_rf_telemetry(
    path: str | Path,
    *,
    max_records: int,
) -> tuple[list[dict[str, Any]], dict[str, object], list[str]]:
    """Read at most ``max_records`` physical JSONL lines with a line-size cap."""

    limit = _positive_bounded("max_records", max_records, MAX_RF_RECORDS_HARD_LIMIT)
    source = Path(path).expanduser().resolve()
    records: list[dict[str, Any]] = []
    warnings: list[str] = []
    lines_examined = 0
    invalid_lines = 0
    overlong_line = False
    truncated_by_limit = False

    with source.open("rb") as handle:
        while lines_examined < limit:
            raw = handle.readline(MAX_JSONL_LINE_BYTES + 1)
            if not raw:
                break
            lines_examined += 1
            if len(raw) > MAX_JSONL_LINE_BYTES:
                overlong_line = True
                invalid_lines += 1
                warnings.append(
                    f"Stopped reading {source.name}: line {lines_examined} exceeds "
                    f"the {MAX_JSONL_LINE_BYTES}-byte safety limit."
                )
                break
            if not raw.strip():
                continue
            try:
                decoded = raw.decode("utf-8-sig")
                value = json.loads(decoded)
                if not isinstance(value, dict):
                    raise ValueError("record is not a JSON object")
            except (UnicodeDecodeError, json.JSONDecodeError, ValueError) as exc:
                invalid_lines += 1
                warnings.append(
                    f"Skipped invalid telemetry line {lines_examined} in {source.name}: {exc}."
                )
                continue
            records.append(value)

        if not overlong_line and lines_examined >= limit:
            truncated_by_limit = bool(handle.read(1))

    if truncated_by_limit:
        warnings.append(
            f"Telemetry processing stopped at the configured {limit}-record limit."
        )
    stats: dict[str, object] = {
        "path": str(source),
        "max_records": limit,
        "lines_examined": lines_examined,
        "json_objects_read": len(records),
        "invalid_lines": invalid_lines,
        "truncated_by_record_limit": truncated_by_limit,
        "stopped_on_overlong_line": overlong_line,
    }
    return records, stats, warnings


def rf_link_to_observation(
    record: Mapping[str, Any],
    *,
    record_index: int,
    fallback_timestamp: datetime,
) -> SensorObservation:
    """Convert one Unreal link record to a gated analytic RF observation.

    The analytic Pd is retained as a measurement.  The public observation
    probability is set to zero when Unreal's final ``detected`` gate is false,
    because that gate includes supported-band, range, sensitivity, and optional
    line-of-sight conditions that an SNR-only equation cannot represent.
    """

    if not isinstance(record, Mapping):
        raise TypeError("record must be a mapping")
    node_id = _nonempty_string("nodeId", record.get("nodeId"))
    target_id = _nonempty_string(
        "targetActor", record.get("targetActor") or record.get("emitterId")
    )
    frequency_ghz = _finite_number("frequencyGHz", record.get("frequencyGHz"))
    if frequency_ghz <= 0.0:
        raise ValueError("frequencyGHz must be > 0")
    snr_db = _finite_number("snrDb", record.get("snrDb"))
    telemetry_detected = record.get("detected")
    if not isinstance(telemetry_detected, bool):
        raise TypeError("detected must be a boolean")
    timestamp, used_fallback_timestamp = _parse_utc_timestamp(
        record.get("timestampUtc"), fallback=fallback_timestamp
    )
    estimate = analytic_energy_detector_probability(
        snr_db,
        ANALYTIC_RF_COMPLEX_SAMPLES,
    )
    gated_probability = (
        estimate.probability_detection if telemetry_detected else 0.0
    )
    measurements: dict[str, object] = {
        "detector_method": estimate.method,
        "is_learned_model_score": False,
        "sirfnet_inference_performed": False,
        "analytic_probability_before_unreal_gate": estimate.probability_detection,
        "unreal_rf_detected_gate": telemetry_detected,
        "unreal_detection_gate_applied": True,
        "snr_db": snr_db,
        "num_complex_samples_assumed": estimate.num_complex_samples,
        "false_alarm_probability_assumed": estimate.false_alarm_probability,
        "calibrated_snr_db": estimate.calibrated_snr_db,
        "timestamp_fallback_used": used_fallback_timestamp,
        "detection_only": True,
    }
    optional_numbers = {
        "received_power_dbm": "receivedPowerDbm",
        "noise_floor_dbm": "noiseFloorDbm",
        "distance_m": "distanceMeters",
        "free_space_path_loss_db": "freeSpacePathLossDb",
        "obstruction_loss_db": "obstructionLossDb",
    }
    for output_name, input_name in optional_numbers.items():
        if input_name in record:
            try:
                measurements[output_name] = _finite_number(input_name, record[input_name])
            except (TypeError, ValueError):
                pass
    for output_name, input_name in (
        ("line_of_sight", "lineOfSight"),
        ("frequency_supported", "frequencySupported"),
        ("in_range", "inRange"),
        ("above_sensitivity", "aboveSensitivity"),
    ):
        if isinstance(record.get(input_name), bool):
            measurements[output_name] = record[input_name]
    if isinstance(record.get("emitterId"), str) and record["emitterId"].strip():
        measurements["emitter_id"] = record["emitterId"].strip()

    return SensorObservation(
        observation_id=f"rf-analytic-{record_index:08d}",
        timestamp=timestamp,
        node_id=node_id,
        modality=SensorModality.RF,
        detection_probability=gated_probability,
        confidence_level=ANALYTIC_RF_CONFIDENCE,
        target_track_id=target_id,
        frequency_hz=frequency_ghz * 1e9,
        model_id=ANALYTIC_FALLBACK_METHOD,
        measurements=measurements,
    )


def _band_label(frequency_hz: float) -> str:
    frequency_ghz = frequency_hz / 1e9
    if abs(frequency_ghz - 2.4) <= 0.05:
        return "2.4 GHz"
    if abs(frequency_ghz - 5.8) <= 0.05:
        return "5.8 GHz"
    return f"{frequency_ghz:.6g} GHz"


def summarize_rf_observations(
    observations: Iterable[SensorObservation],
) -> dict[str, object]:
    """Aggregate RF observations by band, node, and target."""

    groups: dict[tuple[str, str, str], dict[str, Any]] = {}
    total = 0
    telemetry_detections = 0
    for observation in observations:
        if observation.modality is not SensorModality.RF:
            continue
        assert observation.frequency_hz is not None
        assert observation.target_track_id is not None
        key = (
            _band_label(observation.frequency_hz),
            observation.node_id,
            observation.target_track_id,
        )
        group = groups.setdefault(
            key,
            {
                "band": key[0],
                "frequency_hz": observation.frequency_hz,
                "node_id": key[1],
                "target_id": key[2],
                "record_count": 0,
                "unreal_detected_count": 0,
                "snr_db_sum": 0.0,
                "snr_db_min": math.inf,
                "snr_db_max": -math.inf,
                "analytic_probability_sum": 0.0,
                "analytic_probability_max": 0.0,
            },
        )
        snr_db = float(observation.measurements["snr_db"])
        raw_probability = float(
            observation.measurements["analytic_probability_before_unreal_gate"]
        )
        detected = bool(observation.measurements["unreal_rf_detected_gate"])
        group["record_count"] += 1
        group["unreal_detected_count"] += int(detected)
        group["snr_db_sum"] += snr_db
        group["snr_db_min"] = min(group["snr_db_min"], snr_db)
        group["snr_db_max"] = max(group["snr_db_max"], snr_db)
        group["analytic_probability_sum"] += raw_probability
        group["analytic_probability_max"] = max(
            group["analytic_probability_max"], raw_probability
        )
        total += 1
        telemetry_detections += int(detected)

    output_groups: list[dict[str, object]] = []
    for key in sorted(groups):
        group = groups[key]
        count = int(group.pop("record_count"))
        snr_sum = float(group.pop("snr_db_sum"))
        probability_sum = float(group.pop("analytic_probability_sum"))
        raw_probability_max = float(group.pop("analytic_probability_max"))
        output_groups.append(
            {
                **group,
                "record_count": count,
                "unreal_detection_rate": group["unreal_detected_count"] / count,
                "snr_db_mean": snr_sum / count,
                "analytic_probability_mean_before_unreal_gate": probability_sum / count,
                "analytic_probability_max_before_unreal_gate": raw_probability_max,
            }
        )
    return {
        "grouping": "band_node_target",
        "observation_count": total,
        "unreal_detected_count": telemetry_detections,
        "unreal_detection_rate": telemetry_detections / total if total else None,
        "groups": output_groups,
    }


def _bounded_frame_candidates(node_directory: Path, keep: int) -> tuple[list[Path], int]:
    heap: list[tuple[tuple[str, int], str, Path]] = []
    candidate_count = 0
    try:
        entries = node_directory.iterdir()
    except OSError:
        return [], 0
    for path in entries:
        match = _RGB_FRAME_PATTERN.match(path.name)
        if not path.is_file() or match is None:
            continue
        candidate_count += 1
        timestamp_key = match.group("timestamp").replace("fZ", "000000Z")
        sort_key = (timestamp_key, int(match.group("index")))
        item = (sort_key, path.name, path)
        if len(heap) < keep:
            heapq.heappush(heap, item)
        elif item[:2] > heap[0][:2]:
            heapq.heapreplace(heap, item)
    return [item[2] for item in sorted(heap)], candidate_count


def _frame_index(path: Path) -> int | None:
    match = _RGB_FRAME_PATTERN.match(path.name)
    return int(match.group("index")) if match is not None else None


def find_bounded_frame_pairs(
    saved_dir: str | Path,
    *,
    max_pairs: int,
) -> tuple[list[FramePair], dict[str, object], list[str]]:
    """Select recent adjacent RGB pairs fairly across bounded node folders."""

    limit = _positive_bounded("max_pairs", max_pairs, MAX_EVENT_PAIRS_HARD_LIMIT)
    frames_root = Path(saved_dir).expanduser().resolve() / "frames"
    warnings: list[str] = []
    if not frames_root.is_dir():
        return [], {
            "frames_root": str(frames_root),
            "node_directories_examined": 0,
            "timestamped_rgb_frames_found": 0,
            "possible_pairs": 0,
            "selected_pairs": 0,
            "max_pairs": limit,
        }, warnings

    node_directories = sorted(
        (path for path in frames_root.iterdir() if path.is_dir()),
        key=lambda path: path.name,
    )
    if len(node_directories) > MAX_FRAME_NODE_DIRECTORIES:
        warnings.append(
            f"Only the first {MAX_FRAME_NODE_DIRECTORIES} frame node directories were "
            "examined by the safety limit."
        )
        node_directories = node_directories[:MAX_FRAME_NODE_DIRECTORIES]

    pairs_by_node: list[list[FramePair]] = []
    frame_count = 0
    possible_pairs = 0
    for node_directory in node_directories:
        frames, candidate_count = _bounded_frame_candidates(node_directory, limit + 1)
        frame_count += candidate_count
        possible_pairs += max(0, candidate_count - 1)
        node_pairs: list[FramePair] = []
        for index in range(1, len(frames)):
            previous_index = _frame_index(frames[index - 1])
            current_index = _frame_index(frames[index])
            # Frame indices reset at each PIE/Game session.  Requiring adjacent
            # indices avoids manufacturing event stacks across session boundaries.
            if previous_index is None or current_index != previous_index + 1:
                continue
            node_pairs.append(
                FramePair(node_directory.name, frames[index - 1], frames[index])
            )
        if node_pairs:
            pairs_by_node.append(node_pairs)

    selected: list[FramePair] = []
    offset = 0
    while len(selected) < limit:
        added = False
        for node_pairs in pairs_by_node:
            if offset < len(node_pairs):
                selected.append(node_pairs[offset])
                added = True
                if len(selected) >= limit:
                    break
        if not added:
            break
        offset += 1

    return selected, {
        "frames_root": str(frames_root),
        "node_directories_examined": len(node_directories),
        "timestamped_rgb_frames_found": frame_count,
        "possible_pairs": possible_pairs,
        "selected_pairs": len(selected),
        "max_pairs": limit,
    }, warnings


def _load_rgb_image(path: Path) -> NDArray[np.uint8]:
    try:
        from PIL import Image
    except (ImportError, ModuleNotFoundError) as exc:
        raise MissingOptionalDependencyError(
            "Pillow is required to read Unreal PNG frames; install the 'pillow' package "
            "or run with camera-frame processing disabled by supplying a Saved directory "
            "without frame pairs."
        ) from exc
    with Image.open(path) as image:
        return np.asarray(image.convert("RGB"), dtype=np.uint8).copy()


def _filename_timestamp(path: Path) -> datetime | None:
    match = _RGB_FRAME_PATTERN.match(path.name)
    if match is None:
        return None
    raw = match.group("timestamp")
    head = raw[:15]
    fractional = raw[15:-1]
    if fractional.lower() == "f":
        return None
    try:
        base = datetime.strptime(head, "%Y%m%dT%H%M%S")
        microseconds = int(fractional.ljust(6, "0")[:6])
    except (ValueError, TypeError):
        return None
    return base.replace(microsecond=microseconds, tzinfo=timezone.utc)


def _frame_timestamp(path: Path, warnings: list[str]) -> datetime:
    metadata_path = path.with_name(path.name.removesuffix("_rgb.png") + "_depth.json")
    if metadata_path.is_file():
        try:
            with metadata_path.open("rb") as handle:
                raw = handle.read(MAX_FRAME_METADATA_BYTES + 1)
            if len(raw) > MAX_FRAME_METADATA_BYTES:
                raise ValueError("metadata exceeds the 65536-byte safety limit")
            metadata = json.loads(raw.decode("utf-8-sig"))
            fallback = datetime.fromtimestamp(path.stat().st_mtime, tz=timezone.utc)
            timestamp, used_fallback = _parse_utc_timestamp(
                metadata.get("timestampUtc") if isinstance(metadata, dict) else None,
                fallback=fallback,
            )
            if not used_fallback:
                return timestamp
        except (OSError, UnicodeDecodeError, json.JSONDecodeError, ValueError) as exc:
            warnings.append(f"Could not use frame metadata {metadata_path.name}: {exc}.")
    parsed = _filename_timestamp(path)
    if parsed is not None:
        return parsed
    warnings.append(f"Used file mtime because {path.name} has no usable UTC timestamp.")
    return datetime.fromtimestamp(path.stat().st_mtime, tz=timezone.utc)


def process_event_frames(
    saved_dir: str | Path,
    *,
    max_pairs: int,
    skip_inference: bool,
    event_model_path: str | Path,
    event_device: str = "cpu",
) -> tuple[dict[str, object], list[SensorObservation], list[str]]:
    """Project bounded RGB pairs and optionally run the trusted Event-YOLO adapter."""

    pairs, discovery, warnings = find_bounded_frame_pairs(saved_dir, max_pairs=max_pairs)
    per_node: dict[str, dict[str, int]] = defaultdict(
        lambda: {
            "pairs_projected": 0,
            "active_proxy_pixels": 0,
            "event_model_observations": 0,
        }
    )
    observations: list[SensorObservation] = []
    proxy_stacks = 0
    failed_pairs = 0
    inference_attempted = False
    inference_status = "skipped_by_user" if skip_inference else "not_attempted_no_pairs"
    proxy_status = "no_frame_pairs" if not pairs else "pending"

    adapter: EventYOLOAdapter | None = None
    inference_enabled = not skip_inference and bool(pairs)
    if inference_enabled:
        try:
            adapter = EventYOLOAdapter(
                event_model_path,
                max_detections=100,
                device=event_device,
            )
            inference_status = "pending"
        except (ModelBlockedError, TypeError, ValueError) as exc:
            code = getattr(exc, "code", "blocked_adapter_initialization")
            inference_status = str(code)
            inference_enabled = False
            warnings.append(f"Event-YOLO adapter was not initialized: {exc}")

    for pair in pairs:
        try:
            previous = _load_rgb_image(pair.previous_path)
            current = _load_rgb_image(pair.current_path)
        except MissingOptionalDependencyError as exc:
            proxy_status = "blocked_missing_pillow"
            if not skip_inference:
                inference_status = "blocked_missing_pillow"
            warnings.append(str(exc))
            break
        except (OSError, ValueError) as exc:
            failed_pairs += 1
            warnings.append(
                f"Skipped RGB pair for node {pair.node_id}: could not load PNG data ({exc})."
            )
            continue

        previous_timestamp = _frame_timestamp(pair.previous_path, warnings)
        current_timestamp = _frame_timestamp(pair.current_path, warnings)
        delta_seconds = (current_timestamp - previous_timestamp).total_seconds()
        if not math.isfinite(delta_seconds) or delta_seconds < 0.0:
            warnings.append(
                f"Used 1/30 s for non-monotonic frame timestamps at node {pair.node_id}."
            )
            delta_seconds = 1.0 / 30.0
        try:
            projected = project_proxy_event_stack(
                previous,
                current,
                delta_seconds=delta_seconds,
            )
        except (TypeError, ValueError) as exc:
            failed_pairs += 1
            warnings.append(
                f"Skipped RGB pair for node {pair.node_id}: proxy projection failed ({exc})."
            )
            continue

        proxy_stacks += 1
        proxy_status = "completed"
        active_pixels = int(np.count_nonzero(np.any(projected != 0, axis=2)))
        per_node[pair.node_id]["pairs_projected"] += 1
        per_node[pair.node_id]["active_proxy_pixels"] += active_pixels

        if inference_enabled and adapter is not None:
            inference_attempted = True
            try:
                found = adapter.infer(
                    projected,
                    node_id=pair.node_id,
                    timestamp=current_timestamp,
                    frame_id=pair.current_path.stem,
                    source_encoding=PROXY_EVENT_ENCODING,
                )
                observations.extend(found)
                per_node[pair.node_id]["event_model_observations"] += len(found)
                inference_status = "completed"
            except ModelBlockedError as exc:
                inference_status = exc.code
                inference_enabled = False
                warnings.append(f"Event-YOLO inference stopped: {exc}")
            except Exception as exc:  # adapter/runtime boundary; preserve the report
                inference_status = "blocked_unexpected_inference_failure"
                inference_enabled = False
                warnings.append(f"Event-YOLO inference stopped after an unexpected error: {exc}")

    if pairs and proxy_status == "pending":
        proxy_status = "no_pairs_projected"
    if not skip_inference and proxy_stacks and not inference_attempted and inference_status == "pending":
        inference_status = "not_attempted"
    summary: dict[str, object] = {
        **discovery,
        "source_encoding": PROXY_EVENT_ENCODING,
        "preprocessing_equivalent_to_training": False,
        "proxy_status": proxy_status,
        "proxy_stacks_created": proxy_stacks,
        "failed_pairs": failed_pairs,
        "event_model_path": str(Path(event_model_path).expanduser().resolve()),
        "event_model_inference_skipped": skip_inference,
        "event_model_inference_attempted": inference_attempted,
        "event_model_inference_status": inference_status,
        "event_observation_count": len(observations),
        "per_node": [
            {"node_id": node_id, **counts}
            for node_id, counts in sorted(per_node.items())
        ],
    }
    return summary, observations, warnings


def fuse_node_level_evidence(
    rf_observations: Iterable[SensorObservation],
    event_observations: Iterable[SensorObservation],
    *,
    observed_node_ids: Iterable[str] = (),
) -> dict[str, object]:
    """Conservatively retain the strongest positive evidence at each node."""

    evidence_by_node: dict[str, list[ProbabilityEvidence]] = defaultdict(list)
    modalities_by_node: dict[str, set[str]] = defaultdict(set)
    all_nodes = set(observed_node_ids)

    for observation in (*tuple(rf_observations), *tuple(event_observations)):
        all_nodes.add(observation.node_id)
        if observation.detection_probability <= 0.0:
            continue
        confidence = observation.confidence_level
        if observation.modality is SensorModality.RF:
            if not bool(observation.measurements.get("unreal_rf_detected_gate", False)):
                continue
        elif observation.modality is SensorModality.EVENT_CAMERA:
            if observation.measurements.get("source_encoding") == PROXY_EVENT_ENCODING:
                confidence *= PROXY_EVENT_CALIBRATION_DISCOUNT
        else:
            continue
        evidence_by_node[observation.node_id].append(
            ProbabilityEvidence(
                source_id=observation.observation_id,
                probability=observation.detection_probability,
                confidence_level=confidence,
                correlation_group=observation.modality.value,
            )
        )
        modalities_by_node[observation.node_id].add(observation.modality.value)

    results: list[dict[str, object]] = []
    for node_id in sorted(evidence_by_node):
        evidence = evidence_by_node[node_id]
        if not evidence:
            continue
        fused = conservative_confidence_fusion(evidence)
        results.append(
            {
                "node_id": node_id,
                **asdict(fused),
                "supporting_modalities": sorted(modalities_by_node[node_id]),
                "scope": "run-level node evidence; targets are not cross-modally associated",
            }
        )
    result_nodes = {item["node_id"] for item in results}
    return {
        "method": "max_confidence_discounted_evidence_no_independence_v1",
        "status": "completed" if results else "no_detection_evidence",
        "node_result_count": len(results),
        "nodes": results,
        "nodes_without_positive_detection_evidence": sorted(all_nodes - result_nodes),
        "independence_assumed": False,
        "temporal_probability_accumulation": False,
        "target_association_performed": False,
    }


def _model_doctor_report(model_root: str | Path, local_sm: str) -> list[dict[str, object]]:
    return [
        readiness.to_dict()
        for readiness in doctor_models(
            default_model_specs(model_root),
            local_sm=local_sm,
        )
    ]


def run_experiment(
    *,
    saved_dir: str | Path = DEFAULT_SAVED_DIR,
    model_root: str | Path = DEFAULT_MODEL_ROOT,
    event_model_path: str | Path | None = None,
    max_records: int = DEFAULT_MAX_RF_RECORDS,
    max_event_pairs: int = DEFAULT_MAX_EVENT_PAIRS,
    skip_event_inference: bool = False,
    event_device: str = "cpu",
    local_sm: str = "sm70",
) -> dict[str, object]:
    """Run one bounded read-only experiment and return a JSON-safe report."""

    record_limit = _positive_bounded(
        "max_records", max_records, MAX_RF_RECORDS_HARD_LIMIT
    )
    pair_limit = _positive_bounded(
        "max_event_pairs", max_event_pairs, MAX_EVENT_PAIRS_HARD_LIMIT
    )
    saved_path = Path(saved_dir).expanduser().resolve()
    model_path = Path(model_root).expanduser().resolve()
    selected_event_model = (
        Path(event_model_path).expanduser().resolve()
        if event_model_path is not None
        else model_path / DEFAULT_EVENT_MODEL_NAME
    )
    warnings: list[str] = []
    doctor = _model_doctor_report(model_path, local_sm)

    telemetry_path = find_newest_rf_telemetry(saved_path)
    rf_observations: list[SensorObservation] = []
    if telemetry_path is None:
        telemetry_stats: dict[str, object] = {
            "path": None,
            "max_records": record_limit,
            "lines_examined": 0,
            "json_objects_read": 0,
            "invalid_lines": 0,
            "truncated_by_record_limit": False,
            "stopped_on_overlong_line": False,
        }
        warnings.append(
            f"No rf_links_*.jsonl telemetry file was found under {saved_path}."
        )
    else:
        raw_records, telemetry_stats, read_warnings = read_bounded_rf_telemetry(
            telemetry_path,
            max_records=record_limit,
        )
        warnings.extend(read_warnings)
        fallback_timestamp = datetime.fromtimestamp(
            telemetry_path.stat().st_mtime, tz=timezone.utc
        )
        for index, record in enumerate(raw_records):
            try:
                rf_observations.append(
                    rf_link_to_observation(
                        record,
                        record_index=index,
                        fallback_timestamp=fallback_timestamp,
                    )
                )
            except (KeyError, TypeError, ValueError) as exc:
                warnings.append(
                    f"Skipped telemetry object {index + 1} in {telemetry_path.name}: {exc}."
                )

    rf_summary = summarize_rf_observations(rf_observations)
    event_summary, event_observations, event_warnings = process_event_frames(
        saved_path,
        max_pairs=pair_limit,
        skip_inference=skip_event_inference,
        event_model_path=selected_event_model,
        event_device=event_device,
    )
    warnings.extend(event_warnings)
    observed_nodes = {observation.node_id for observation in rf_observations}
    observed_nodes.update(
        str(item["node_id"])
        for item in event_summary["per_node"]
        if isinstance(item, dict) and "node_id" in item
    )
    fusion = fuse_node_level_evidence(
        rf_observations,
        event_observations,
        observed_node_ids=observed_nodes,
    )

    limitations = [
        "Detection-only simulation: this package contains no engagement, interception, "
        "weapon-control, damage, or effector logic.",
        "User-supplied RF checkpoints are excluded. RF evidence uses only the declared "
        "simulation link budget and analytic detector path.",
        "RF probabilities use an uncalibrated analytic Gaussian/CLT energy-detector fallback "
        "with 256 assumed complex samples, then apply Unreal's final boolean RF gate.",
        "Unreal RF propagation is a link-budget and collision-line-trace approximation, not a "
        "full electromagnetic solver; Cesium collision availability can affect line of sight.",
        "proxy_event_stack_v1 is generated from adjacent RGB frames and is not equivalent to "
        "the custom FRED event-stack preprocessing used to train the event checkpoint.",
        "The supplied RGB-D TensorRT plan is not executed because it targets sm120 while this "
        "deployment host is sm70; no RGB-D observations are fabricated.",
        "Fusion keeps only the strongest confidence-discounted node evidence, assumes no "
        "sensor independence, performs no temporal accumulation, and does not associate "
        "event boxes to RF target identities.",
    ]
    return {
        "schema_version": "1.0",
        "experiment_kind": "bounded_one_shot_detection_only",
        "generated_at_utc": datetime.now(timezone.utc)
        .isoformat(timespec="microseconds")
        .replace("+00:00", "Z"),
        "scope": {
            "simulation_only": True,
            "detection_only": True,
            "engagement_logic_present": False,
        },
        "inputs": {
            "saved_dir": str(saved_path),
            "model_root": str(model_path),
            "max_rf_records": record_limit,
            "max_event_frame_pairs": pair_limit,
            "event_device": event_device,
        },
        "model_doctor": doctor,
        "rf": {
            "inference_kind": ANALYTIC_FALLBACK_METHOD,
            "is_sirfnet_inference": False,
            "telemetry": telemetry_stats,
            "summary": rf_summary,
            "observation_samples": [
                observation.to_dict()
                for observation in rf_observations[:MAX_OBSERVATION_SAMPLES]
            ],
        },
        "event_camera": {
            **event_summary,
            "observation_samples": [
                observation.to_dict()
                for observation in event_observations[:MAX_OBSERVATION_SAMPLES]
            ],
        },
        "rgbd": {
            "observation_count": 0,
            "inference_performed": False,
            "status": "blocked_incompatible_runtime_hardware",
        },
        "fusion": fusion,
        "warnings": _deduplicate(warnings),
        "limitations": limitations,
    }


def write_report_atomic(report: Mapping[str, Any], output_path: str | Path) -> Path:
    """Atomically replace a UTF-8 JSON report in its destination directory."""

    destination = Path(output_path).expanduser().resolve()
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary_path: Path | None = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            dir=destination.parent,
            prefix=f".{destination.name}.",
            suffix=".tmp",
            delete=False,
        ) as handle:
            temporary_path = Path(handle.name)
            json.dump(report, handle, indent=2, allow_nan=False)
            handle.write("\n")
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary_path, destination)
    except Exception:
        if temporary_path is not None:
            temporary_path.unlink(missing_ok=True)
        raise
    return destination


def _bounded_cli_integer(name: str, hard_limit: int):
    def parse(value: str) -> int:
        try:
            number = int(value)
        except ValueError as exc:
            raise argparse.ArgumentTypeError(f"{name} must be an integer") from exc
        try:
            return _positive_bounded(name, number, hard_limit)
        except (TypeError, ValueError) as exc:
            raise argparse.ArgumentTypeError(str(exc)) from exc

    return parse


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--saved-dir",
        type=Path,
        default=DEFAULT_SAVED_DIR,
        help="Unreal Saved/SingaporeSensorFusion directory.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=None,
        help="Destination JSON report (default: <saved-dir>/experiment_report_latest.json).",
    )
    parser.add_argument(
        "--model-root",
        type=Path,
        default=DEFAULT_MODEL_ROOT,
        help="Directory containing the four supplied artifacts.",
    )
    parser.add_argument(
        "--event-model",
        type=Path,
        default=None,
        help="Override the supplied Event-YOLO checkpoint path.",
    )
    parser.add_argument(
        "--max-records",
        type=_bounded_cli_integer("max_records", MAX_RF_RECORDS_HARD_LIMIT),
        default=DEFAULT_MAX_RF_RECORDS,
        help="Maximum telemetry lines examined.",
    )
    parser.add_argument(
        "--max-event-pairs",
        type=_bounded_cli_integer("max_event_pairs", MAX_EVENT_PAIRS_HARD_LIMIT),
        default=DEFAULT_MAX_EVENT_PAIRS,
        help="Maximum adjacent RGB frame pairs projected across all nodes.",
    )
    parser.add_argument(
        "--skip-event-inference",
        action="store_true",
        help="Create proxy event stacks but do not load or run Event-YOLO.",
    )
    parser.add_argument(
        "--event-device",
        default="cpu",
        help="Ultralytics device string (default: cpu).",
    )
    parser.add_argument(
        "--local-sm",
        default="sm70",
        help="Deployment CUDA compute-capability label used by the model doctor.",
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = _build_parser().parse_args(argv)
    output = args.output or args.saved_dir / "experiment_report_latest.json"
    report = run_experiment(
        saved_dir=args.saved_dir,
        model_root=args.model_root,
        event_model_path=args.event_model,
        max_records=args.max_records,
        max_event_pairs=args.max_event_pairs,
        skip_event_inference=args.skip_event_inference,
        event_device=args.event_device,
        local_sm=args.local_sm,
    )
    written = write_report_atomic(report, output)
    print(f"Wrote bounded detection experiment report: {written}")
    print(
        "RF observations: "
        f"{report['rf']['summary']['observation_count']}; "
        "event observations: "
        f"{report['event_camera']['event_observation_count']}; "
        f"fused nodes: {report['fusion']['node_result_count']}"
    )
    return 0


if __name__ == "__main__":  # pragma: no cover - exercised through ``python -m``
    raise SystemExit(main())
